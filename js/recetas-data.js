/* Se conserva una copia limpia para "Restaurar recetas originales".
   Migración de datos del prototipo anterior: actualiza ingredientes y pasos
   según Recetario.rar, conservando otras ediciones y recetas creadas por el usuario. */
(() => {
  const currentKey = 'cran_ensenada_recetas_v2';
  const oldKey = 'cran_ensenada_recetas_v1';
  const originals = window.CRAN_RECETAS;
  window.CRAN_RECETAS_ORIGINALES = originals.map(r => ({
    ...r, ingredients: [...r.ingredients], steps: [...r.steps]
  }));
  const valid = recipes => Array.isArray(recipes) && recipes.length <= 120 && recipes.every(
    r => r && Number.isInteger(r.id) && typeof r.title === 'string' &&
      Array.isArray(r.ingredients) && Array.isArray(r.steps)
  );
  try {
    const alreadyUpdated = JSON.parse(localStorage.getItem(currentKey));
    if (valid(alreadyUpdated)) {
      window.CRAN_RECETAS = alreadyUpdated;
      return;
    }
    const previous = JSON.parse(localStorage.getItem(oldKey));
    if (!valid(previous)) return;
    const byId = new Map(originals.map(r => [r.id, r]));
    const migrated = previous.map(recipe => {
      const source = byId.get(recipe.id);
      if (!source) return recipe; // Las recetas nuevas del administrador permanecen.
      return {
        ...recipe,
        ingredients: [...source.ingredients],
        steps: [...source.steps],
        stepsCount: source.steps.length
      };
    });
    window.CRAN_RECETAS = migrated;
    localStorage.setItem(currentKey, JSON.stringify(migrated));
  } catch (error) {
    console.warn('No se pudieron cargar las recetas locales.', error);
  }
})();
